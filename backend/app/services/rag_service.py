import os
import re
import logging
from typing import List, Dict, Any, Optional
import chromadb
from chromadb.config import Settings as ChromaSettings
from sqlalchemy.orm import Session
from backend.app.models.document_chunk import DocumentChunk

logger = logging.getLogger("campusflow.rag_service")

CHROMA_PERSIST_DIR = os.path.abspath("./data/chroma")
os.makedirs(CHROMA_PERSIST_DIR, exist_ok=True)

class RAGService:
    def __init__(self):
        try:
            self.client = chromadb.PersistentClient(path=CHROMA_PERSIST_DIR)
            self.collection = self.client.get_or_create_collection(
                name="campusflow_academic_knowledge",
                metadata={"hnsw:space": "cosine"}
            )
            logger.info("ChromaDB vector store initialized at: %s", CHROMA_PERSIST_DIR)
        except Exception as e:
            logger.error("Failed to initialize ChromaDB PersistentClient: %s. Using in-memory client.", e)
            self.client = chromadb.Client()
            self.collection = self.client.get_or_create_collection(
                name="campusflow_academic_knowledge",
                metadata={"hnsw:space": "cosine"}
            )

    @staticmethod
    def chunk_text(text: str, chunk_size: int = 400, overlap: int = 50) -> List[Dict[str, Any]]:
        """
        Split document text into clean, contextual chunks preserving page numbers.
        Detects '--- Page X ---' headers generated by document_service.
        """
        chunks: List[Dict[str, Any]] = []
        pages = re.split(r"\n--- Page (\d+)(?: \([^)]+\))? ---\n", text)

        if len(pages) > 1:
            # First element is preamble before Page 1
            idx = 1
            while idx < len(pages):
                page_num = int(pages[idx])
                page_content = pages[idx + 1].strip()
                idx += 2

                # Chunk this page
                sentences = re.split(r"(?<=[.!?\n])\s+", page_content)
                current_chunk = ""
                chunk_idx = 0

                for s in sentences:
                    if len(current_chunk) + len(s) > chunk_size and current_chunk:
                        chunks.append({
                            "page_number": page_num,
                            "chunk_index": chunk_idx,
                            "content": current_chunk.strip()
                        })
                        chunk_idx += 1
                        # Retain overlap from end of current chunk
                        current_chunk = current_chunk[-overlap:] + " " + s
                    else:
                        current_chunk += (" " if current_chunk else "") + s

                if current_chunk.strip():
                    chunks.append({
                        "page_number": page_num,
                        "chunk_index": chunk_idx,
                        "content": current_chunk.strip()
                    })
        else:
            # Single-page or plain pasted text
            words = text.split()
            current_words: List[str] = []
            chunk_idx = 0
            for w in words:
                current_words.append(w)
                if len(" ".join(current_words)) >= chunk_size:
                    chunks.append({
                        "page_number": 1,
                        "chunk_index": chunk_idx,
                        "content": " ".join(current_words)
                    })
                    chunk_idx += 1
                    current_words = current_words[-10:]  # overlap

            if current_words:
                chunks.append({
                    "page_number": 1,
                    "chunk_index": chunk_idx,
                    "content": " ".join(current_words)
                })

        return chunks

    def ingest_document(
        self,
        user_id: int,
        document_id: int,
        document_name: str,
        text: str,
        source_type: str,
        db: Session
    ) -> int:
        """
        Full RAG Ingestion Pipeline:
        1. Chunks document text with page attribution.
        2. Saves chunks into PostgreSQL relational table (DocumentChunk).
        3. Generates embeddings and indexes into ChromaDB with user_id metadata.
        """
        raw_chunks = self.chunk_text(text)
        if not raw_chunks:
            return 0

        # Delete any existing chunks for this document in ChromaDB
        self.delete_document(user_id, document_id, db=None)

        ids = []
        documents = []
        metadatas = []

        for c in raw_chunks:
            chunk_id = f"user_{user_id}_doc_{document_id}_p{c['page_number']}_c{c['chunk_index']}"
            ids.append(chunk_id)
            documents.append(c["content"])
            metadatas.append({
                "user_id": str(user_id),
                "document_id": str(document_id),
                "document_name": document_name,
                "page_number": int(c["page_number"]),
                "chunk_index": int(c["chunk_index"]),
                "source_type": source_type
            })

            # Also persist in PostgreSQL
            db_chunk = DocumentChunk(
                user_id=user_id,
                announcement_id=document_id,
                document_name=document_name,
                page_number=c["page_number"],
                chunk_index=c["chunk_index"],
                content=c["content"],
                source_type=source_type
            )
            db.add(db_chunk)

        db.commit()

        # Add to ChromaDB
        self.collection.add(
            ids=ids,
            documents=documents,
            metadatas=metadatas
        )
        logger.info("Ingested %d vector chunks for user %d document '%s'", len(ids), user_id, document_name)
        return len(ids)

    def search_similar_context(
        self,
        user_id: int,
        query: str,
        top_k: int = 3,
        threshold: float = 0.85
    ) -> List[Dict[str, Any]]:
        """
        Semantic similarity retrieval with strict user-level metadata isolation.
        Returns top matching chunks with document and page attribution.
        """
        try:
            results = self.collection.query(
                query_texts=[query],
                n_results=top_k,
                where={"user_id": str(user_id)}
            )
        except Exception as e:
            logger.error("ChromaDB query error: %s", e)
            return []

        retrieved: List[Dict[str, Any]] = []
        if not results or not results.get("documents") or not results["documents"][0]:
            return []

        docs = results["documents"][0]
        metas = results["metadatas"][0] if results.get("metadatas") else [{}] * len(docs)
        distances = results["distances"][0] if results.get("distances") else [0.0] * len(docs)

        for doc, meta, dist in zip(docs, metas, distances):
            retrieved.append({
                "content": doc,
                "document_name": meta.get("document_name", "Academic Notice"),
                "document_id": meta.get("document_id"),
                "page_number": meta.get("page_number", 1),
                "source_type": meta.get("source_type", "pdf"),
                "distance": round(float(dist), 4)
            })

        return retrieved

    def delete_document(self, user_id: int, document_id: int, db: Optional[Session] = None):
        """Remove document chunks from both ChromaDB vector index and PostgreSQL."""
        try:
            self.collection.delete(
                where={"$and": [{"user_id": str(user_id)}, {"document_id": str(document_id)}]}
            )
        except Exception as e:
            logger.warning("Could not delete from ChromaDB by compound filter: %s", e)

        if db:
            db.query(DocumentChunk).filter(
                DocumentChunk.user_id == user_id,
                DocumentChunk.announcement_id == document_id
            ).delete()
            db.commit()

    def reindex_all_for_user(self, user_id: int, db: Session) -> int:
        """Rebuild user's vector embeddings from relational database records."""
        # Clear user's Chroma collection
        try:
            self.collection.delete(where={"user_id": str(user_id)})
        except Exception:
            pass

        chunks = db.query(DocumentChunk).filter(DocumentChunk.user_id == user_id).all()
        if not chunks:
            return 0

        ids = [f"user_{c.user_id}_doc_{c.announcement_id}_p{c.page_number}_c{c.chunk_index}" for c in chunks]
        docs = [c.content for c in chunks]
        metas = [{
            "user_id": str(c.user_id),
            "document_id": str(c.announcement_id),
            "document_name": c.document_name,
            "page_number": c.page_number,
            "chunk_index": c.chunk_index,
            "source_type": c.source_type
        } for c in chunks]

        self.collection.add(ids=ids, documents=docs, metadatas=metas)
        return len(chunks)

rag_service = RAGService()
